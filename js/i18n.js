  var I18N = {
    lang: 'en',
    listeners: [],

    setLang: function (lang) {
      if (!DICT[lang]) lang = 'en';
      this.lang = lang;
      document.documentElement.setAttribute('lang', lang);
      this.apply();
      for (var i = 0; i < this.listeners.length; i++) {
        try { this.listeners[i](lang); } catch (e) {}
      }
    },

    onChange: function (fn) { this.listeners.push(fn); },

    t: function (key) {
      var d = DICT[this.lang] || EN;
      var s = d[key];
      if (s === undefined) s = EN[key];
      if (s === undefined) s = RU[key];
      if (s === undefined) return key;
      if (arguments.length > 1) {
        for (var i = 1; i < arguments.length; i++) {
          s = s.split('{' + (i - 1) + '}').join(String(arguments[i]));
        }
      }
      return s;
    },

    /* Применяет перевод ко всем элементам с data-i18n */
    apply: function (root) {
      root = root || document;
      var nodes = root.querySelectorAll('[data-i18n]');
      for (var i = 0; i < nodes.length; i++) {
        var el = nodes[i];
        el.textContent = this.t(el.getAttribute('data-i18n'));
      }
      var attrs = root.querySelectorAll('[data-i18n-title]');
      for (var j = 0; j < attrs.length; j++) {
        attrs[j].setAttribute('title', this.t(attrs[j].getAttribute('data-i18n-title')));
      }
    },

    available: ['ru', 'en', 'tr'],
    labels: { ru: 'Русский', en: 'English', tr: 'Türkçe' }
  };

